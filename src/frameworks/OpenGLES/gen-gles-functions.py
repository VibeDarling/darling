#!/usr/bin/env python3
"""
Generates src/gles-functions.c, OpenGLES.framework's GL entry points, from
Khronos's GLES headers (an NDK's sysroot has all of them):

    gen-gles-functions.py <include dir> > src/gles-functions.c

Each entry point is a trampoline that jumps to the host's function, found the
first time it is called (gles_resolve in EAGLContext.m). The trampolines
leave every argument register alone, so one shape fits every signature.

The exception is a function some of whose arguments are on the stack in
different places for Apple's arm64 ABI and the host's (AAPCS64): Apple's packs
stack arguments by their size, AAPCS64 gives each 8 bytes. Those get a C
wrapper that passes the stack arguments as 8-byte values.
"""
import re
import sys

HEADERS = ["GLES/gl.h", "GLES/glext.h", "GLES2/gl2.h", "GLES2/gl2ext.h",
           "GLES3/gl3.h", "GLES3/gl31.h", "GLES3/gl32.h"]

PROTO = re.compile(r"^GL_API(?:CALL)?\s+(.+?)\s*GL_APIENTRY\s+(gl\w+)\s*\((.*)\);")

FLOAT_TYPES = {"GLfloat", "GLclampf"}
DOUBLE_TYPES = {"GLdouble"}
SIZE8 = {"GLint64", "GLuint64", "GLint64EXT", "GLuint64EXT", "GLintptr", "GLsizeiptr",
         "GLintptrEXT", "GLsizeiptrEXT", "GLsync", "GLeglImageOES", "GLeglClientBufferEXT",
         "GLDEBUGPROC", "GLDEBUGPROCKHR"}
SIZE1 = {"GLboolean", "GLbyte", "GLubyte", "GLchar"}
SIZE2 = {"GLshort", "GLushort", "GLhalf"}


def params(text):
    text = text.strip()
    if text in ("", "void"):
        return []
    out = []
    for p in text.split(","):
        p = p.strip()
        m = re.match(r"(.*?)(\w+)\s*(\[\d*\])?$", p)
        ptype, name = m.group(1).strip(), m.group(2)
        if m.group(3) or "*" in ptype:
            kind, size = "gp", 8
        else:
            base = ptype.replace("const", "").strip()
            if base in FLOAT_TYPES:
                kind, size = "fp", 4
            elif base in DOUBLE_TYPES:
                kind, size = "fp", 8
            elif base in SIZE8:
                kind, size = "gp", 8
            elif base in SIZE1:
                kind, size = "gp", 1
            elif base in SIZE2:
                kind, size = "gp", 2
            else:
                kind, size = "gp", 4
        out.append((ptype, name, kind, size))
    return out


def stack_offsets(args):
    """(apple, aapcs) stack offsets of the arguments past the registers."""
    gp = fp = 0
    apple = aapcs = 0
    result = []
    for ptype, name, kind, size in args:
        if kind == "gp" and gp < 8:
            gp += 1
            continue
        if kind == "fp" and fp < 8:
            fp += 1
            continue
        apple = (apple + size - 1) // size * size
        result.append((name, apple, aapcs))
        apple += size
        aapcs += 8
    return result


def main():
    root = sys.argv[1]
    functions = {}
    for header in HEADERS:
        for line in open(f"{root}/{header}"):
            m = PROTO.match(line.strip())
            if m and m.group(2) not in functions:
                functions[m.group(2)] = (m.group(1).strip(), params(m.group(3)))

    print("/* Generated by gen-gles-functions.py from Khronos's GLES headers: do not edit. */")
    print("#define GLES_FUNCTIONS_C")
    print("#include \"gles-functions.h\"")
    print()
    for name in sorted(functions):
        ret, args = functions[name]
        stack = stack_offsets(args)
        print(f"GLES_SLOT({name})")
        if all(apple == aapcs for _, apple, aapcs in stack):
            print(f"GLES_TRAMPOLINE({name})")
            continue
        # The stack arguments, as the host reads them: each in its own 8 bytes.
        on_stack = {n for n, _, _ in stack}
        decl = ", ".join(f"{t} {n}" for t, n, _, _ in args)
        host = ", ".join(("double" if k == "fp" else "uint64_t") if n in on_stack else t
                         for t, n, k, _ in args)
        call = ", ".join(f"gles_stack_{'fp' if k == 'fp' else 'gp'}(&{n}, sizeof({n}))" if n in on_stack else n
                         for t, n, k, _ in args)
        ret_kw = "" if ret == "void" else "return "
        print(f"{ret} {name}({decl})")
        print("{")
        print(f"\t{ret_kw}(({ret} (*)({host}))gles_resolve(&gles_slot_{name}))({call});")
        print("}")
    print()
    print(f"/* {len(functions)} functions. */")


main()

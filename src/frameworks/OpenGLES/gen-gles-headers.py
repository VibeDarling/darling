#!/usr/bin/env python3
"""
Generates OpenGLES.framework's GL headers, in iOS's layout, from Khronos's GLES headers (the
OpenGL-Registry's api/ directory, or an NDK sysroot's include directory):

    gen-gles-headers.py <include dir> include/OpenGLES

    OpenGLES/gltypes.h          the GL types
    OpenGLES/ES1/gl.h, glext.h  from GLES/gl.h, GLES/glext.h
    OpenGLES/ES2/gl.h, glext.h  from GLES2/gl2.h, GLES2/gl2ext.h
    OpenGLES/ES3/gl.h, glext.h  from GLES3/gl3.h, GLES2/gl2ext.h

As iOS's, they include no platform header: the types are gltypes.h's, GL_API is extern and
GL_APIENTRY empty, the extensions' prototypes are declared without GL_GLEXT_PROTOTYPES, and there
are no PFNGL...PROC function pointer types. The
functions are the ones src/gles-functions.c exports, which gen-gles-functions.py makes from the
same headers.
"""
import os
import re
import sys

GLTYPES = """\
/* Generated by gen-gles-headers.py: do not edit. */

#ifndef __gltypes_h_
#define __gltypes_h_

#include <stdint.h>

typedef uint32_t GLbitfield;
typedef uint8_t GLboolean;
typedef int8_t GLbyte;
typedef float GLclampf;
typedef uint32_t GLenum;
typedef float GLfloat;
typedef int32_t GLint;
typedef int16_t GLshort;
typedef int32_t GLsizei;
typedef uint8_t GLubyte;
typedef uint32_t GLuint;
typedef uint16_t GLushort;
typedef void GLvoid;
typedef char GLchar;
typedef int32_t GLclampx;
typedef int32_t GLfixed;
typedef uint16_t GLhalf;
typedef int64_t GLint64;
typedef struct __GLsync *GLsync;
typedef uint64_t GLuint64;
typedef intptr_t GLintptr;
typedef intptr_t GLsizeiptr;

#endif
"""

PREAMBLE = """\
#include <OpenGLES/gltypes.h>

#ifndef GL_API
#define GL_API extern
#endif
#ifndef GL_APICALL
#define GL_APICALL GL_API
#endif
#ifndef GL_APIENTRY
#define GL_APIENTRY
#endif
#ifndef GL_APIENTRYP
#define GL_APIENTRYP GL_APIENTRY*
#endif
"""

OUTPUTS = [
    ("ES1/gl.h", "GLES/gl.h", "__OPENGLES_ES1_GL_H_"),
    ("ES1/glext.h", "GLES/glext.h", "__OPENGLES_ES1_GLEXT_H_"),
    ("ES2/gl.h", "GLES2/gl2.h", "__OPENGLES_ES2_GL_H_"),
    ("ES2/glext.h", "GLES2/gl2ext.h", "__OPENGLES_ES2_GLEXT_H_"),
    ("ES3/gl.h", "GLES3/gl3.h", "__OPENGLES_ES3_GL_H_"),
    ("ES3/glext.h", "GLES2/gl2ext.h", "__OPENGLES_ES3_GLEXT_H_"),
]

# The types gltypes.h has; Khronos's headers each typedef them from khrplatform.h.
BASIC_TYPEDEF = re.compile(r"^typedef\s+[\w\s\*]+?\b(GL(?:bitfield|boolean|byte|clampf|enum|float|int|short|"
                           r"sizei|ubyte|uint|ushort|void|char|clampx|fixed|half|int64|sync|uint64|intptr|"
                           r"sizeiptr))\s*;\s*$")
# iOS's headers declare no function pointer types: code that wants them defines its own.
PFN_TYPEDEF = re.compile(r"^typedef\s.*\(\s*GL_APIENTRYP\s+PFNGL\w+PROC\s*\)")
PLATFORM_INCLUDE = re.compile(r"^#include\s+<(KHR/khrplatform\.h|GLES\d?/gl\d?platform\.h)>\s*$")
# The extension headers include the core header of their API; ours name the iOS path.
CORE_INCLUDE = re.compile(r"^#include\s+<GLES(\d?)/gl(\d?)\.h>\s*$")


KHRONOS_TYPES = {
    "khronos_int8_t": "int8_t", "khronos_uint8_t": "uint8_t", "khronos_int16_t": "int16_t",
    "khronos_uint16_t": "uint16_t", "khronos_int32_t": "int32_t", "khronos_uint32_t": "uint32_t",
    "khronos_int64_t": "int64_t", "khronos_uint64_t": "uint64_t", "khronos_float_t": "float",
    "khronos_intptr_t": "intptr_t", "khronos_ssize_t": "intptr_t", "khronos_uintptr_t": "uintptr_t",
    "khronos_usize_t": "uintptr_t", "khronos_utime_nanoseconds_t": "uint64_t",
    "khronos_stime_nanoseconds_t": "int64_t",
}
KHRONOS_TYPE = re.compile(r"\b(" + "|".join(KHRONOS_TYPES) + r")\b")


def convert(text, guard, api_dir):
    text = KHRONOS_TYPE.sub(lambda m: KHRONOS_TYPES[m.group(1)], text)
    lines = text.splitlines()
    out = []
    pending_endif = False
    depth = 0
    for line in lines:
        stripped = line.strip()
        if PLATFORM_INCLUDE.match(stripped):
            continue
        if BASIC_TYPEDEF.match(stripped) or PFN_TYPEDEF.match(stripped):
            continue
        if CORE_INCLUDE.match(stripped):
            out.append("#include <OpenGLES/%s/gl.h>" % api_dir)
            continue
        if stripped == "#ifdef GL_GLEXT_PROTOTYPES":
            pending_endif = True
            depth = 0
            continue
        if pending_endif:
            if re.match(r"#\s*if", stripped):
                depth += 1
            elif re.match(r"#\s*endif", stripped):
                if depth == 0:
                    pending_endif = False
                    continue
                depth -= 1
        out.append(line)
    body = "\n".join(out) + "\n"
    return ("/* Generated by gen-gles-headers.py from Khronos's headers: do not edit. */\n\n"
            "#ifndef %s\n#define %s 1\n\n%s\n%s\n#endif /* %s */\n" % (guard, guard, PREAMBLE, body, guard))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source, dest = sys.argv[1], sys.argv[2]
    with open(os.path.join(dest, "gltypes.h"), "w") as f:
        f.write(GLTYPES)
    for out_name, in_name, guard in OUTPUTS:
        with open(os.path.join(source, in_name)) as f:
            text = f.read()
        os.makedirs(os.path.join(dest, os.path.dirname(out_name)), exist_ok=True)
        with open(os.path.join(dest, out_name), "w") as f:
            f.write(convert(text, guard, os.path.dirname(out_name)))


if __name__ == "__main__":
    main()
